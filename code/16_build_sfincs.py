# ================= 5. rainfall =================
P = np.load(os.path.join(PTH.IRMA['raw'], 'mrms_cache/mrms_P.npy'))            # (240, 40, 57) row 0 = north
LL = np.load(os.path.join(PTH.IRMA['raw'], 'mrms_cache/mrms_lonlat.npy'))
lon_min, lon_max, lat_min, lat_max, dlon, dlat = LL
nlat, nlon = P.shape[1], P.shape[2]
lons = lon_min + np.arange(nlon) * abs(dlon)
lats = lat_max - np.arange(nlat) * abs(dlat)          # row 0 = north
n_nonfinite = int((~np.isfinite(P)).sum())
assert n_nonfinite == 0, 'MRMS cache contains %d non-finite values -- no filling, fix the data first' % n_nonfinite
P = np.clip(P, 0, None)

# ---- the rainfall grid (1 km) extends beyond the SFINCS model domain: 1 km west / east / south, 2 km north ----
# Based on runs/_tests/ampr_roworder (2026-09-15): SFINCS does not use row 1 of the ampr file (northernmost row) and does not extrapolate beyond the centre of the northernmost valid row;
# with a 1 km extension the northernmost 2 model rows (400 m) still got no rain (T2), so the north side is extended by one more row. All extended cells fall inside the MRMS cache and take real values; no zero-filling, no extrapolation.
DXR = 1000.0
RAIN_MARGIN = dict(w=1, e=1, s=1, n=2)                  # unit: number of 1 km cells
AX0, AX1 = R['xmin'] - RAIN_MARGIN['w'] * DXR, R['xmax'] + RAIN_MARGIN['e'] * DXR
AY0, AY1 = R['ymin'] - RAIN_MARGIN['s'] * DXR, R['ymax'] + RAIN_MARGIN['n'] * DXR
ncol, nrow = int(round((AX1 - AX0) / DXR)), int(round((AY1 - AY0) / DXR))
xr = AX0 + (np.arange(ncol) + 0.5) * DXR
yr = AY1 - (np.arange(nrow) + 0.5) * DXR                # row 0 = north
XR, YR = np.meshgrid(xr, yr)
LO, LA = geoio.utm_to_ll(XR.ravel(), YR.ravel(), ZONE)
ci_raw = np.round((LO - lons[0]) / abs(dlon)).astype(int)
ri_raw = np.round((lats[0] - LA) / abs(dlat)).astype(int)
inside_mask = (ci_raw >= 0) & (ci_raw < nlon) & (ri_raw >= 0) & (ri_raw < nlat)
inside = float(inside_mask.mean())
assert inside == 1.0, '%d cells of the extended rainfall grid fall outside the MRMS cache -- no extrapolation, enlarge the MRMS window first' % int((~inside_mask).sum())
ci, ri = ci_raw, ri_raw
PR = P[:, ri, ci].reshape(P.shape[0], nrow, ncol)      # (240, nrow, ncol) nearest neighbour
# self-check: every SFINCS active cell centre lies within the "valid coverage" of ampr (envelope of cell centres after removing file row 1)
_xc = X0 + (np.arange(MMAX) + 0.5) * DX200; _yc = Y0 + (np.arange(NMAX) + 0.5) * DX200
_XC, _YC = np.meshgrid(_xc, _yc)
_valid = (_XC >= xr[0]) & (_XC <= xr[-1]) & (_YC >= yr[-1]) & (_YC <= yr[1])   # yr[1] = centre of row 2 (row 1 is ignored by SFINCS)
_uncov = int((ACT & ~_valid).sum())
