"""
16_build_sfincs.py -- translate the prepared data into SFINCS native input files (200 m computational grid)

Output directory: Flood_2.0/sfincs_200m/
  sfincs.inp                 main control file (grid, time, physical parameters, file list)
  sfincs.ind / .msk / .dep   computational grid index / mask / bed elevation (binary, inputformat = bin)
  sfincs.bnd / .bzs          water-level boundary point coordinates / water-level time series (Mayport native 6 min)
  sfincs.src / .dis          discharge source point coordinates / discharge time series (Acosta native 15 min, split by cross-section)
  sfincs.ampr                spatial rainfall (Delft3D meteo ASCII, 1 km equidistant UTM grid, MRMS nearest-neighbour values)
  sfincs.precip              areal-mean rainfall (alternative for uniform rainfall, not enabled in inp)
  sfincs.obs                 observation points (9 stations, for his output)
  qgis/                      200 m dep / msk GeoTIFFs, boundary / source / observation point GeoJSON -- for checking in QGIS
  alt/                       hourly-mean versions of bzs / dis (alternative)
  sfincs_build.json          machine-readable record (resampling statistics, edge closure, source splitting, per-file checks)

Conventions:
  * Binary layout follows hydromt_sfincs: array (nmax, mmax), n=1 is south; flattened in column-major order, only active cells written.
  * tref = tstart = window start 2017-09-06 00:00 UTC; all time series are given as "seconds since tref".
  * Hourly rainfall accumulation P(T) represents [T-1h, T), written as mm/hr at the interval start T-1h (forward blocks), with one extra record at the end.
  * Roughness: three keywords manning_land / manning_sea + rgh_lev_land, no manningfile.
This script does not run SFINCS; none of the files have been validated by SFINCS itself -- see 'not_validated' in sfincs_build.json.
"""
