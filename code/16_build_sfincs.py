# active-domain edge cells (at least one of the four neighbours inactive)
_pad = np.zeros((NMAX + 2, MMAX + 2), bool); _pad[1:-1, 1:-1] = ACT
EDGE = ACT & ~(_pad[:-2, 1:-1] & _pad[2:, 1:-1] & _pad[1:-1, :-2] & _pad[1:-1, 2:])


def grow(cells):
    out = set()
    for n, m in cells:
        for dn in (-1, 0, 1):
            for dm in (-1, 0, 1):
                a, b = n + dn, m + dm
                if 0 <= a < NMAX and 0 <= b < MMAX:
                    out.add((a, b))
    return out


# The 60 m boundary lines "straddle cells" on the 200 m grid: if a cell crossed by the line is inactive (e.g. more than half seaward), the
# water-level boundary is placed on the active edge cells within its 8-neighbourhood, so that coast / estuary boundaries stay continuous at 200 m.
bnd_cells, bnd_info = [], []
for pts, p in DWL:
    cs = cells_of(pts)
    on = [(n, m) for (n, m) in cs if ACT[n, m]]
    nb = [(n, m) for (n, m) in grow(cs) if ACT[n, m] and EDGE[n, m] and (n, m) not in set(on)]
    for n, m in on + nb:
        MSK[n, m] = 2
    bnd_cells += on + nb
    zz = [Z[n, m] for n, m in on + nb]
    bnd_info.append(dict(bnd_id=p['bnd_id'], line_cells=len(cs), line_cells_active=len(on),
                         neighbour_edge_cells_added=len(nb), msk2_cells=len(on) + len(nb),
                         z_min_200m=round(float(min(zz)), 2) if zz else None))
    print('  %s: line crosses %d 200 m cells (%d active) + %d neighbouring edge cells -> msk=2 total %d'
          % (p['bnd_id'], len(cs), len(on), len(nb), len(on) + len(nb)))

# Boundary points: one point every BND_SPACING_M along the DW lines (all pointing to the same Mayport series)
bnd_pts = []
for pts, p in DWL:
    d = densify(pts, 5.0)
    seg = np.hypot(*(d[1:] - d[:-1]).T)
    s = np.concatenate([[0], np.cumsum(seg)])
    L = s[-1]
    nn = max(2, int(np.floor(L / BND_SPACING_M)) + 1)
    for t in np.linspace(0, L, nn):
        k = int(np.searchsorted(s, t))
        k = min(k, len(d) - 1)
        bnd_pts.append((float(d[k, 0]), float(d[k, 1]), p['bnd_id']))
print('  water-level boundary points: %d' % len(bnd_pts))

# Source points: active water cells crossed by UP01, split by (-z * dx)
src_pts = []
for pts, p in UPL:
    cs0 = cells_of(pts)
    cs = [(n, m) for (n, m) in cs0 if ACT[n, m]]
    # likewise merge active water cells on the domain edge within the line's 8-neighbourhood into the source cells (at 200 m the channel section is wider than the cells crossed by the line)
    nb = [(n, m) for (n, m) in grow(cs0) if ACT[n, m] and EDGE[n, m] and Z[n, m] <= 0
          and (n, m) not in set(cs)]
