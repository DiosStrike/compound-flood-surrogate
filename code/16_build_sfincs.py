# ================= 2. boundary lines -> 200 m cells =================
def gj_lines(path):
    d = json.load(open(path)); out = []
    for f in d['features']:
        g = f['geometry']
        if not g or not g.get('coordinates'):
            continue
        segs = [g['coordinates']] if g['type'] == 'LineString' else g['coordinates']
        pts = []
        for s in segs:
            a = np.asarray(s, float)
            x, y = geoio.ll_to_utm(a[:, 0], a[:, 1], ZONE)
            pts.append(np.c_[x, y])
        out.append((np.vstack(pts), f['properties']))
    return out


def densify(p, step=25.0):
    o = [p[0]]
    for a, b in zip(p[:-1], p[1:]):
        n = max(1, int(np.ceil(float(np.hypot(*(b - a))) / step)))
        for k in range(1, n + 1):
            o.append(a + (b - a) * (k / n))
    return np.array(o)


def cells_of(pts):
    p = densify(pts)
    m = np.floor((p[:, 0] - X0) / DX200).astype(int)
    n = np.floor((p[:, 1] - Y0) / DX200).astype(int)
    ok = (m >= 0) & (m < MMAX) & (n >= 0) & (n < NMAX)
    seen, out = set(), []
    for a, b in zip(n[ok], m[ok]):
        if (a, b) not in seen:
            seen.add((a, b)); out.append((a, b))
    return out


MSK = np.where(ACT, 1, 0).astype(np.uint8)
